#!/usr/bin/env node
/*
 * Freezes agreement.html into the signup Worker: _worker/src/agreement.generated.js
 *   - html:   the exact agreement markup the signup page shows (between the two markers)
 *   - sha256: SHA-256 of that markup (the same fingerprint as agreementHash in js/signup-config.js)
 *   - blocks: the same text as headings/paragraphs/list items, used to print the signed PDF
 * Run after every agreement change:  node _tools/build-agreement-module.js
 * Add --fonts once to (re)generate Helvetica widths from @pdf-lib/standard-fonts (dev-only package).
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const config = require(path.join(ROOT, 'js', 'signup-config.js'));

function extract(html) {
  const start = html.indexOf('<div id="agreement-text">');
  const end = html.indexOf('<!-- /agreement-text -->');
  if (start < 0 || end < start) throw new Error('agreement markers not found');
  return html.slice(start, end);
}

const ENT = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", nbsp: ' ', mdash: '—', ndash: '–', rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', hellip: '…' };
const decode = (s) => s.replace(/&(#\d+|#x[0-9a-f]+|\w+);/gi, (m, e) => {
  if (e[0] === '#') return String.fromCodePoint(e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
  return ENT[e] !== undefined ? ENT[e] : m;
});

// headings, paragraphs and list items → [{type, runs:[{b, t}]}]; bold kept, other tags flattened
function toBlocks(seg) {
  const blocks = [];
  const re = /<(h1|h3|p|li)\b([^>]*)>([\s\S]*?)<\/\1>/g;
  let m;
  while ((m = re.exec(seg))) {
    const type = m[1] === 'p' && /class="muted"/.test(m[2]) ? 'meta' : m[1];
    const runs = [];
    const parts = m[3].split(/(<strong>[\s\S]*?<\/strong>)/);
    for (const part of parts) {
      if (!part) continue;
      const bold = part.startsWith('<strong>');
      const text = decode(part.replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ');
      if (text) runs.push({ b: bold || type === 'h1' || type === 'h3', t: text });
    }
    if (runs.length) { runs[0].t = runs[0].t.replace(/^\s+/, ''); runs[runs.length - 1].t = runs[runs.length - 1].t.replace(/\s+$/, ''); blocks.push({ type, runs }); }
  }
  return blocks;
}

function buildFonts() {
  const { Font, FontNames, Encodings } = require('@pdf-lib/standard-fonts');
  const out = {};
  for (const [key, name] of [['regular', FontNames.Helvetica], ['bold', FontNames.HelveticaBold]]) {
    const f = Font.load(name);
    const widths = new Array(256).fill(0);
    // map every WinAnsi code → width via unicode round-trip
    for (let cp = 32; cp < 0x2200; cp++) {
      let enc; try { enc = Encodings.WinAnsi.encodeUnicodeCodePoint(cp); } catch (e) { continue; }
      if (enc && enc.code < 256) widths[enc.code] = f.getWidthOfGlyph(enc.name) || widths[enc.code];
    }
    out[key] = widths;
  }
  // unicode → WinAnsi code for the non-Latin-1 characters WinAnsi supports
  const map = {};
  for (let cp = 0x100; cp < 0x2200; cp++) {
    try { const enc = Encodings.WinAnsi.encodeUnicodeCodePoint(cp); if (enc && enc.code < 256) map[cp] = enc.code; } catch (e) { /* not encodable */ }
  }
  out.unicodeToWinAnsi = map;
  fs.writeFileSync(path.join(ROOT, '_worker', 'src', 'fonts.generated.js'),
    '// Generated by _tools/build-agreement-module.js --fonts from @pdf-lib/standard-fonts (Adobe Helvetica AFM metrics). Do not edit.\n' +
    'export const WIDTHS = ' + JSON.stringify({ regular: out.regular, bold: out.bold }) + ';\n' +
    'export const UNICODE_TO_WINANSI = ' + JSON.stringify(out.unicodeToWinAnsi) + ';\n');
}

if (process.argv.includes('--fonts')) buildFonts();
const seg = extract(fs.readFileSync(path.join(ROOT, 'agreement.html'), 'utf8'));
const sha256 = crypto.createHash('sha256').update(seg, 'utf8').digest('hex');
const blocks = toBlocks(seg);
if (sha256 !== config.agreementHash) {
  console.error(`agreementHash in js/signup-config.js (${config.agreementHash}) ≠ agreement.html (${sha256}). Bump agreementVersion and run: npm run agreement-hash`);
  process.exit(1);
}
const out = '// Generated by _tools/build-agreement-module.js from agreement.html. Do not edit by hand.\n' +
  'export const AGREEMENT = ' + JSON.stringify({ version: config.agreementVersion, sha256, html: seg, blocks }, null, 0) + ';\n';
fs.writeFileSync(path.join(ROOT, '_worker', 'src', 'agreement.generated.js'), out);
console.log(`agreement v${config.agreementVersion} sha256 ${sha256} — ${blocks.length} blocks`);
module.exports = { extract, toBlocks };
