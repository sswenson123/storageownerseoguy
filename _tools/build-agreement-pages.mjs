#!/usr/bin/env node
// Pre-lays-out the agreement pages for the signed PDF (same for every signer) so signing only lays out
// the certificate page — keeps /api/sign/complete well inside the Workers Free plan CPU limit.
// Run after build-agreement-module.js (npm run agreement-pdf does both).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AGREEMENT } from '../_worker/src/agreement.generated.js';
import { agreementPageBodies } from '../_worker/src/pdf.js';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const bodies = agreementPageBodies(AGREEMENT.blocks);
fs.writeFileSync(path.join(ROOT, '_worker', 'src', 'agreement-pages.generated.js'),
  '// Generated by _tools/build-agreement-pages.mjs from agreement.generated.js. Do not edit by hand.\n' +
  'export const AGREEMENT_PAGES = ' + JSON.stringify({ version: AGREEMENT.version, sha256: AGREEMENT.sha256, bodies }) + ';\n');
console.log(`agreement v${AGREEMENT.version}: ${bodies.length} pre-built pages`);
